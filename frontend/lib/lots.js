export function money(n, forceCents = false) {
  const v = Number(n) || 0;
  if (forceCents || Math.round(v * 100) % 100 !== 0) {
    return `$${v.toFixed(2)}`;
  }
  return `$${v.toFixed(0)}`;
}

export function sizePrice(lot, sizeId) {
  if (lot.category === "gear" || lot.category === "husk") {
    return lot.price;
  }
  const size = SIZES.find((s) => s.id === sizeId) || SIZES[1];
  if (size.trade) return null;
  return Math.round(lot.price * size.factor);
}

export function subscribePrice(price) {
  return Math.round(price * 0.85 * 100) / 100;
}

