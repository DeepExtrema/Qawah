/*
 * Attach each lot's catalogue image, which ships in frontend/public/products
 * named after the lot's slug. Applied here rather than repeated on all 18
 * objects, so the two can never drift apart.
 *
 * This matters beyond tidiness: mergeWithApi falls back to these definitions
 * when the API is unreachable, and takes `hit.imageUrl || lot.imageUrl`.
 * Without an imageUrl here, an API outage turned every product card into a
 * grey placeholder rather than degrading to the real photo with mock pricing.
 */
export const LOTS = LOT_DEFS.map((lot) => ({
  ...lot,
  imageUrl: lot.imageUrl || (lot.slug ? `/products/${lot.slug}.png` : ""),
}));


export function getLot(id) {
  return LOTS.find((lot) => lot._id === id || lot.slug === id);
}

export function shopLots() {
  return LOTS.filter((lot) => lot.category === "coffee" || lot.category === "husk");
}

export function gearLots() {
  return LOTS.filter((lot) => lot.category === "gear");
}

export function inStockLots() {
  return shopLots().filter((lot) => !lot.soldOut);
}

export function mergeWithApi(apiProducts) {
  if (!Array.isArray(apiProducts) || apiProducts.length === 0) return LOTS;
  return LOTS.map((lot) => {
    const hit = apiProducts.find(
      (p) =>
        p &&
        typeof p.name === "string" &&
        p.name.toLowerCase() === lot.name.toLowerCase()
    );
    if (!hit) return lot;
    return {
      ...lot,
      mockId: lot._id,
      _id: hit._id || lot._id,
      price: typeof hit.price === "number" ? hit.price : lot.price,
      inventory:
        typeof hit.inventory === "number" ? hit.inventory : lot.inventory,
      soldOut:
        typeof hit.soldOut === "boolean"
          ? hit.soldOut
          : typeof hit.inventory === "number"
            ? hit.inventory <= 0
            : lot.soldOut,
      category: hit.category || lot.category,
      story: hit.story || lot.story,
      imageUrl: hit.imageUrl || lot.imageUrl,
      images: Array.isArray(hit.images) && hit.images.length ? hit.images : lot.images,
      roast: hit.roast || lot.roast,
      origin: hit.origin || lot.origin,
      notes: Array.isArray(hit.notes) ? hit.notes : lot.notes,
      slug: hit.slug || lot.slug,
    };
  });
}

